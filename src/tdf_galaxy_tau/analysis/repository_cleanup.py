"""Repository cleanup audit and safe release hygiene (no science changes)."""

from __future__ import annotations

import csv
import os
import re
import shutil
from collections import Counter
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable

AUDIT_VERSION = "zenodo_release_prep_v1"

CATEGORIES = (
    "keep_core",
    "keep_data",
    "keep_outputs_frozen",
    "keep_paper",
    "keep_docs",
    "cleanup_candidate",
    "archive_candidate",
)

SKIP_DIR_NAMES = {".git", ".venv", "node_modules"}

LATEX_BUILD_SUFFIXES = {
    ".aux",
    ".log",
    ".out",
    ".bbl",
    ".blg",
    ".fls",
    ".fdb_latexmk",
}

CLEANUP_DIR_NAMES = {"__pycache__", ".pytest_cache"}

CLEANUP_FILE_NAMES = {".DS_Store"}

# Paths always treated as frozen scientific / publication outputs.
FROZEN_OUTPUT_PREFIXES = (
    "outputs/tables/",
    "outputs/reports/",
    "outputs/figures/sparc_subset/",
)

# LaTeX aux under paper/ (regenerated by compile_paper_pdf).
PAPER_SOURCE_NAMES = {
    "manuscript.tex",
    "manuscript.pdf",
    "references.bib",
    "README.md",
}

REQUIRED_BENCHMARK_CSVS = (
    "outputs/tables/controlled_expansion_comparison_summary.csv",
    "outputs/tables/controlled_expansion_final_claims.csv",
    "outputs/tables/expansion20_holdout_validation.csv",
    "outputs/tables/expansion20_failure_mode_summary.csv",
    "outputs/tables/paper_statistical_summary.csv",
)


@dataclass(frozen=True)
class FileRecord:
    rel_path: str
    category: str
    size_bytes: int
    referenced: bool
    reference_hits: str
    action: str
    notes: str


def _repo_files(root: Path) -> list[Path]:
    out: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIR_NAMES]
        base = Path(dirpath)
        if any(part in SKIP_DIR_NAMES for part in base.relative_to(root).parts):
            continue
        for name in filenames:
            p = base / name
            if p.is_file():
                out.append(p)
    return sorted(out)


def _reference_corpus(root: Path) -> str:
    globs = [
        "README.md",
        "docs/**/*.md",
        "paper/**/*.md",
        "paper/**/*.tex",
        "paper/**/*.bib",
        "scripts/**/*.py",
        "tests/**/*.py",
        "configs/**/*.yaml",
        "src/**/*.py",
    ]
    chunks: list[str] = []
    for pattern in globs:
        for path in sorted(root.glob(pattern)):
            if path.is_file() and ".git" not in path.parts:
                try:
                    chunks.append(path.read_text(encoding="utf-8", errors="replace"))
                except OSError:
                    pass
    return "\n".join(chunks)


def _path_reference_hits(rel: str, corpus: str) -> list[str]:
    posix = rel.replace("\\", "/")
    hits: list[str] = []
    candidates = {posix, posix.split("/")[-1]}
    if posix.startswith("outputs/"):
        candidates.add(posix[len("outputs/") :])
    for cand in candidates:
        if len(cand) >= 4 and cand in corpus:
            hits.append(cand)
    return sorted(set(hits))


def _is_latex_build_artifact(rel: str) -> bool:
    p = Path(rel)
    if p.parent.name != "paper" or p.name.startswith("manuscript."):
        return p.suffix in LATEX_BUILD_SUFFIXES
    return False


def _classify(rel: str, *, referenced: bool, corpus: str) -> tuple[str, str, str]:
    """Return (category, action, notes)."""
    posix = rel.replace("\\", "/")
    parts = Path(posix).parts

    if any(part in CLEANUP_DIR_NAMES for part in parts):
        return "cleanup_candidate", "delete", "cache directory"
    if Path(posix).name in CLEANUP_FILE_NAMES:
        return "cleanup_candidate", "delete", "OS metadata file"

    if _is_latex_build_artifact(posix):
        return "cleanup_candidate", "delete", "LaTeX build artifact (regenerated by compile)"

    if posix.startswith("src/"):
        return "keep_core", "keep", "library source"
    if posix.startswith("scripts/"):
        return "keep_core", "keep", "reproducibility script"
    if posix.startswith("configs/"):
        return "keep_core", "keep", "run configuration"
    if posix.startswith("tests/"):
        return "keep_core", "keep", "test suite"
    if posix in {"README.md", "pyproject.toml", "requirements.txt", ".gitignore"}:
        return "keep_core", "keep", "project metadata"

    if posix.startswith("data/raw/sparc/") or posix.startswith("data/processed/"):
        return "keep_data", "keep", "SPARC raw or processed inputs"

    if posix.startswith("paper/"):
        name = Path(posix).name
        if name in PAPER_SOURCE_NAMES or posix.startswith("paper/figures/") or posix.startswith(
            "paper/tables/"
        ):
            return "keep_paper", "keep", "manuscript package asset"
        if posix.endswith(".gitkeep"):
            return "keep_paper", "keep", "directory placeholder"
        return "keep_paper", "keep", "paper directory file"

    if posix.startswith("docs/"):
        return "keep_docs", "keep", "project documentation"

    if any(posix.startswith(prefix) for prefix in FROZEN_OUTPUT_PREFIXES):
        return "keep_outputs_frozen", "keep", "benchmark or publication output"

    if posix.startswith("outputs/"):
        if referenced:
            return "keep_outputs_frozen", "keep", "referenced output artifact"
        return (
            "archive_candidate",
            "archive_if_unreferenced",
            "output not matched to frozen prefixes; check before archive",
        )

    if posix.startswith(".vscode/"):
        return "cleanup_candidate", "delete", "local IDE settings (not for release)"

    if posix.startswith("archive/"):
        return "keep_docs", "keep", "archived historical artifact"

    return "keep_core", "keep", "default keep"


def build_file_inventory(root: Path | str = ".") -> list[FileRecord]:
    root = Path(root).resolve()
    corpus = _reference_corpus(root)
    records: list[FileRecord] = []
    for path in _repo_files(root):
        rel = path.relative_to(root).as_posix()
        hits = _path_reference_hits(rel, corpus)
        referenced = bool(hits)
        category, action, notes = _classify(rel, referenced=referenced, corpus=corpus)
        if category == "archive_candidate" and referenced:
            category = "keep_outputs_frozen"
            action = "keep"
            notes = "referenced; kept despite nonstandard path"
        records.append(
            FileRecord(
                rel_path=rel,
                category=category,
                size_bytes=path.stat().st_size,
                referenced=referenced,
                reference_hits="; ".join(hits[:5]),
                action=action,
                notes=notes,
            )
        )
    return records


def records_to_dataframe_rows(records: Iterable[FileRecord]) -> list[dict[str, object]]:
    return [
        {
            "rel_path": r.rel_path,
            "category": r.category,
            "size_bytes": r.size_bytes,
            "referenced": r.referenced,
            "reference_hits": r.reference_hits,
            "action": r.action,
            "notes": r.notes,
        }
        for r in records
    ]


def write_inventory_csv(records: list[FileRecord], out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(
            fh,
            fieldnames=[
                "rel_path",
                "category",
                "size_bytes",
                "referenced",
                "reference_hits",
                "action",
                "notes",
            ],
        )
        writer.writeheader()
        for row in records_to_dataframe_rows(records):
            writer.writerow(row)


def cleanup_candidates_csv(records: list[FileRecord], out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    candidates = [r for r in records if r.category in {"cleanup_candidate", "archive_candidate"}]
    with out.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(
            fh,
            fieldnames=[
                "rel_path",
                "category",
                "action",
                "referenced",
                "reference_hits",
                "notes",
            ],
        )
        writer.writeheader()
        for r in candidates:
            writer.writerow(
                {
                    "rel_path": r.rel_path,
                    "category": r.category,
                    "action": r.action,
                    "referenced": r.referenced,
                    "reference_hits": r.reference_hits,
                    "notes": r.notes,
                }
            )


def benchmark_csv_mtimes(root: Path) -> dict[str, float]:
    root = Path(root)
    return {
        rel: (root / rel).stat().st_mtime
        for rel in REQUIRED_BENCHMARK_CSVS
        if (root / rel).is_file()
    }


def write_audit_report(
    *,
    root: Path,
    records: list[FileRecord],
    report_out: Path,
    mtimes_before: dict[str, float],
    mtimes_after: dict[str, float] | None = None,
    cleanup_actions: list[str] | None = None,
) -> None:
    counts = Counter(r.category for r in records)
    cleanup = [r for r in records if r.category == "cleanup_candidate"]
    archive = [r for r in records if r.category == "archive_candidate"]
    referenced_archive = [r for r in archive if r.referenced]

    lines = [
        "# Repository cleanup audit report",
        "",
        f"- **Audit version:** `{AUDIT_VERSION}`",
        f"- **Generated (UTC):** {datetime.now(timezone.utc).isoformat()}",
        f"- **Repository root:** `{root.resolve()}`",
        "",
        "## Classification summary",
        "",
        "| Category | Count |",
        "| --- | ---: |",
    ]
    for cat in CATEGORIES:
        lines.append(f"| `{cat}` | {counts.get(cat, 0)} |")
    lines.extend(
        [
            "",
            "## Dependency / reference check",
            "",
            "Reference corpus scanned: `README.md`, `docs/*.md`, `paper/*`, `scripts/*.py`, "
            "`tests/*.py`, `configs/*.yaml`, `src/**/*.py`.",
            "",
            f"- Files marked referenced: {sum(1 for r in records if r.referenced)}",
            f"- Archive candidates (total): {len(archive)}",
            f"- Archive candidates also referenced (kept): {len(referenced_archive)}",
            "",
            "## Safe cleanup policy applied",
            "",
            "- Delete: `__pycache__/`, `.pytest_cache/`, `.DS_Store`, LaTeX aux under `paper/`.",
            "- Do **not** delete raw/processed SPARC data, expansion outputs, paper assets, or "
            "referenced reports/tables.",
            "- Archive: only unreferenced nonessential outputs; none moved in this pass unless "
            "listed in cleanup actions below.",
            "",
            "## Benchmark CSV mtime check",
            "",
        ]
    )
    for rel, before in mtimes_before.items():
        after = (mtimes_after or mtimes_before).get(rel)
        status = "unchanged" if after == before else "CHANGED"
        lines.append(f"- `{rel}`: {status}")
    if cleanup_actions:
        lines.extend(["", "## Cleanup actions performed", ""])
        for action in cleanup_actions:
            lines.append(f"- {action}")
    lines.extend(
        [
            "",
            "## Cleanup candidates (delete)",
            "",
        ]
    )
    for r in cleanup[:40]:
        lines.append(f"- `{r.rel_path}` — {r.notes}")
    if len(cleanup) > 40:
        lines.append(f"- … and {len(cleanup) - 40} more (see `repository_cleanup_candidates.csv`)")
    lines.extend(["", "## Archive candidates", ""])
    if not archive:
        lines.append("- None identified for archival (all outputs referenced or frozen).")
    else:
        for r in archive[:30]:
            flag = " **referenced — keep**" if r.referenced else ""
            lines.append(f"- `{r.rel_path}` — {r.notes}{flag}")
    lines.extend(
        [
            "",
            "## Artifacts",
            "",
            "- `outputs/tables/repository_file_inventory.csv`",
            "- `outputs/tables/repository_cleanup_candidates.csv`",
            "- `docs/repository_cleanup_plan.md`",
            "",
        ]
    )
    report_out.parent.mkdir(parents=True, exist_ok=True)
    report_out.write_text("\n".join(lines), encoding="utf-8")


def apply_safe_cleanup(root: Path | str = ".") -> list[str]:
    """Remove caches, OS junk, and LaTeX build artifacts only."""
    root = Path(root).resolve()
    actions: list[str] = []

    for dirpath, dirnames, _ in os.walk(root, topdown=False):
        base = Path(dirpath)
        if ".git" in base.parts:
            continue
        for name in list(dirnames):
            if name in CLEANUP_DIR_NAMES:
                target = base / name
                shutil.rmtree(target, ignore_errors=True)
                actions.append(f"removed directory {target.relative_to(root).as_posix()}/")

    for path in _repo_files(root):
        rel = path.relative_to(root).as_posix()
        if Path(rel).name in CLEANUP_FILE_NAMES:
            path.unlink(missing_ok=True)
            actions.append(f"deleted file {rel}")
        elif _is_latex_build_artifact(rel):
            path.unlink(missing_ok=True)
            actions.append(f"deleted LaTeX artifact {rel}")

    vscode = root / ".vscode"
    if vscode.is_dir():
        shutil.rmtree(vscode, ignore_errors=True)
        actions.append("removed directory .vscode/")

    return actions


def run_audit(root: Path | str = ".") -> dict[str, object]:
    root = Path(root).resolve()
    records = build_file_inventory(root)
    mtimes_before = benchmark_csv_mtimes(root)

    write_inventory_csv(records, root / "outputs/tables/repository_file_inventory.csv")
    cleanup_candidates_csv(records, root / "outputs/tables/repository_cleanup_candidates.csv")

    write_audit_report(
        root=root,
        records=records,
        report_out=root / "outputs/reports/repository_cleanup_audit_report.md",
        mtimes_before=mtimes_before,
    )

    counts = Counter(r.category for r in records)
    return {
        "n_files": len(records),
        "counts": dict(counts),
        "mtimes_before": mtimes_before,
        "inventory": root / "outputs/tables/repository_file_inventory.csv",
        "candidates": root / "outputs/tables/repository_cleanup_candidates.csv",
        "report": root / "outputs/reports/repository_cleanup_audit_report.md",
    }


def finalize_after_cleanup(
    cleanup_actions: list[str],
    root: Path | str = ".",
    *,
    mtimes_before: dict[str, float] | None = None,
) -> None:
    root = Path(root).resolve()
    records = build_file_inventory(root)
    mtimes_after = benchmark_csv_mtimes(root)
    before = mtimes_before if mtimes_before is not None else mtimes_after
    write_inventory_csv(records, root / "outputs/tables/repository_file_inventory.csv")
    cleanup_candidates_csv(records, root / "outputs/tables/repository_cleanup_candidates.csv")
    write_audit_report(
        root=root,
        records=records,
        report_out=root / "outputs/reports/repository_cleanup_audit_report.md",
        mtimes_before=before,
        mtimes_after=mtimes_after,
        cleanup_actions=cleanup_actions,
    )
